class SVG:
 def __init__(self,name,w,h,title):
  self.name=name;self.w=w;self.h=h
  self.p=[f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" role="img" aria-labelledby="title desc"><title id="title">{escape(title)}</title><desc id="desc">教学示意。带文字的箭头分别表示数据、配置、事件与时钟复位；不是布局图或仿真波形。</desc><defs>']
  for k,c in C.items():self.p.append(f'<marker id="{k}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0 0L10 5L0 10Z" fill="{c}"/></marker>')
  self.p.append('</defs><rect width="100%" height="100%" fill="#fff"/>')
  self.text(30,38,title,25,bold=True)
  self.text(30,65,'教学示意 · 据本地 RTL 整理 · 控制/数据箭头表示请求或事件方向，AXI 响应沿反向返回',15)
 def text(self,x,y,t,size=16,color='#263e50',bold=False):
  self.p.append(f'<text x="{x}" y="{y}" font-family="Noto Sans CJK SC,Microsoft YaHei,sans-serif" font-size="{size}" fill="{color}"'+(' font-weight="700"'if bold else '')+f'>{escape(t)}</text>')
 def group(self,x,y,w,h,title):
  self.p.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="12" fill="#f5f8fa" stroke="#abbfcc" stroke-dasharray="7 4"/>');self.text(x+15,y+26,title,17,bold=True)
 def box(self,x,y,w,h,title,*lines,kind='data'):
  self.p.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="8" fill="#fff" stroke="{C[kind]}" stroke-width="2"/>')
  self.text(x+12,y+26,title,18,C[kind],True)
  for i,line in enumerate(lines):self.text(x+12,y+50+i*23,line,15)
 def arrow(self,pts,label='',kind='data',lx=None,ly=None):
  self.p.append(f'<polyline points="{" ".join(f"{x},{y}"for x,y in pts)}" fill="none" stroke="{C[kind]}" stroke-width="2.2" marker-end="url(#{kind})"'+(' stroke-dasharray="6 4"'if kind in ('irq','clock')else '')+'/>')
  if label:self.text(lx if lx is not None else pts[0][0]+8,ly if ly is not None else pts[0][1]-8,label,14,C[kind])
 def save(self):
  self.text(30,self.h-20,'蓝：配置/控制   绿：数据事务   橙虚线：中断/异常   紫虚线：时钟/复位   灰：阶段或说明',14)
  (ROOT/self.name).write_text('\n'.join(self.p)+'</svg>\n')

