class Diagram:
 def __init__(self,name,title,subtitle,height=560):
  self.name=name;self.h=height
  self.s=[f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1060 {height}" role="img" aria-labelledby="title desc"><title id="title">{e(title)}</title><desc id="desc">{e(subtitle)}</desc><defs><marker id="arrow" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path d="M0,0 L8,4 L0,8" fill="#357988"/></marker></defs><rect width="1060" height="{height}" fill="#fcfefe"/><style>text{{font-family:system-ui,"Noto Sans CJK SC",sans-serif;fill:#17384a}}.title{{font-size:25px;font-weight:700}}.small{{font-size:15px;fill:#536b78}}.box{{font-size:18px}}.label{{font-size:16px;fill:#216c77}}</style>']
  self.text(32,42,title,'title');self.text(32,74,subtitle,'small')
 def text(self,x,y,t,cls='box',anchor='start'):
  self.s.append(f'<text x="{x}" y="{y}" class="{cls}" text-anchor="{anchor}">{e(t)}</text>')
 def box(self,x,y,w,h,*lines,color='#edf5f7'):
  self.s.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="9" fill="{color}" stroke="#a7c2cb"/>')
  for i,l in enumerate(lines):self.text(x+w/2,y+h/2+(i-(len(lines)-1)/2)*26+6,l,anchor='middle')
 def arrow(self,x,y,x2,y2,label='',lx=None,ly=None):
  self.s.append(f'<path d="M{x},{y} L{x2},{y2}" fill="none" stroke="#357988" stroke-width="2" marker-end="url(#arrow)"/>')
  if label:self.text(lx if lx is not None else (x+x2)/2,ly if ly is not None else (y+y2)/2-9,label,'label','middle')
 def note(self,y,t):self.text(32,y,t,'small')
 def save(self):(ROOT/'assets'/f'new-{self.name}.svg').write_text('\n'.join(self.s)+ '</svg>\n')

