ROOT=Path(__file__).resolve().parent
COL={'call':'#4775AC','bus':'#287D70','data':'#8660A5','event':'#BB6D30'}
class Fig:
 def __init__(self,title):
  self.s=['<svg xmlns="http://www.w3.org/2000/svg" width="1400" height="900" viewBox="0 0 1400 900">','<defs>']
  for k,c in COL.items(): self.s.append(f'<marker id="{k}" markerUnits="strokeWidth" markerWidth="3" markerHeight="3" viewBox="0 0 3 3" refX="3" refY="1.5" orient="auto-start-reverse"><polygon points="0,0 3,1.5 0,3" fill="{c}"/></marker>')
  self.s+=['</defs>','<rect x="0" y="0" width="1400" height="900" fill="#FAFCFF"/>'];self.text(48,55,title,30,bold=True)
 def text(self,x,y,t,size=22,color='#26384B',bold=False,anchor='start'):
  self.s.append(f'<text x="{x}" y="{y}" font-family="Microsoft YaHei" font-size="{size}" font-weight="{"bold" if bold else "normal"}" text-anchor="{anchor}" fill="{color}">{escape(t)}</text>')
 def box(self,x,y,w,h,title,lines=(),kind='call'):
  colors={'call':'#EAF1FC','bus':'#E9F5F1','data':'#F1ECF7','event':'#FFF2E5'}
  self.s.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="9" fill="{colors[kind]}" stroke="{COL[kind]}" stroke-width="2"/>')
  self.text(x+w/2,y+36,title,23,bold=True,anchor='middle')
  for i,t in enumerate(lines):self.text(x+w/2,y+70+29*i,t,20,anchor='middle')
 def arrow(self,pts,label='',kind='call',lx=None,ly=None,dash=False,both=False):
  att=f' marker-end="url(#{kind})"'+(f' marker-start="url(#{kind})"' if both else '')+(' stroke-dasharray="8 5"' if dash else '')
  self.s.append(f'<polyline points="{" ".join(f"{x},{y}" for x,y in pts)}" fill="none" stroke="{COL[kind]}" stroke-width="2.4"{att}/>')
  if label:self.text(lx,ly,label,19,COL[kind],anchor='middle')
 def save(self,name):
  (ROOT/f'{name}.svg').write_text('\n'.join(self.s+['</svg>'])+'\n')
