class Fig:
 def __init__(self,n,slug,title,sub):
  self.n=n; self.slug=slug;self.title=title; self.items=[];self.nodes={};self.edges=[];self.count=0
  self.add('<rect id="background" width="1600" height="900" fill="#FFFFFF" stroke="none"/>')
  self.txt(50,57,f'{n:02d}  {title}',34,bold=True)
  self.txt(50,99,sub,21,color=P['muted'])
 def add(self,s): self.items.append(s)
 def ident(self,prefix):self.count+=1;return f'{prefix}-{self.count}'
 def txt(self,x,y,s,size=22,color=None,anchor='start',bold=False):
  self.add(f'<text id="{self.ident("text")}" x="{x}" y="{y}" font-family="Microsoft YaHei" font-size="{size}" font-weight="{"bold" if bold else "normal"}" fill="{color or P["ink"]}" text-anchor="{anchor}">{html.escape(s)}</text>')
 def rect(self,x,y,w,h,fill,stroke='#A4B3BF',dash=False,r=12,id=None):
  self.add(f'<rect id="{id or self.ident("rect")}" x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{fill}" stroke="{stroke}" stroke-width="2"'+(' stroke-dasharray="9 6"' if dash else '')+'/>')
 def box(self,key,x,y,w,h,lines,kind='data',dash=False):
  self.nodes[key]=[x,y,w,h];self.rect(x,y,w,h,F.get(kind,kind),P.get(kind,'#9AABBA'),dash,id=key)
  if isinstance(lines,str):lines=[lines]
  for i,line in enumerate(lines):self.txt(x+w/2,y+h/2+(i-(len(lines)-1)/2)*30+8,line,22,anchor='middle',bold=i==0)
 def group(self,x,y,w,h,title,kind='neutral',dash=False):
  self.rect(x,y,w,h,F[kind], '#B7C4D0',dash,r=16);self.txt(x+20,y+32,title,22,bold=True)
 def edge(self,key,points,kind='data',both=False,dash=False,label=None,at=None):
  assert len(points)>=2 and points[0]!=points[1] and points[-1]!=points[-2]
  color=P[kind];v=' '.join(f'{x},{y}' for x,y in points)
  geom=f'<line id="{key}" x1="{points[0][0]}" y1="{points[0][1]}" x2="{points[1][0]}" y2="{points[1][1]}"' if len(points)==2 else f'<polyline id="{key}" points="{v}"'
  self.add(geom+f' fill="none" stroke="{color}" stroke-width="3" marker-end="url(#arrow-{kind})"'+(f' marker-start="url(#arrow-{kind})"' if both else '')+(' stroke-dasharray="9 6"' if dash else '')+'/>')
  self.edges.append({'id':key,'kind':kind,'points':points,'bidirectional':both})
  if label:
   assert at;self.txt(*at,label,20,color=color,anchor='middle')
 def note(self,x,y,s,kind='muted',size=21):self.txt(x,y,s,size,P[kind])
 def save(self,d):
  # One shared legend; dashed borders mean optional scope, never implementation status.
  for x,k,l in [(55,'data','数据 / 请求'),(340,'control','配置 / 控制'),(625,'done','完成 / 交接'),(910,'error','故障 / 恢复')]:
   self.edge(f'legend-{k}',[(x,858),(x+48,858)],k);self.txt(x+63,865,l,19,color=P[k])
  self.txt(1535,865,f'{self.n:02d} / 13',19,anchor='end',color=P['muted'])
  defs=''.join(f'<marker id="arrow-{k}" markerUnits="strokeWidth" markerWidth="3" markerHeight="3" viewBox="0 0 3 3" refX="3" refY="1.5" orient="auto-start-reverse"><polygon points="0,0 3,1.5 0,3" fill="{P[k]}"/></marker>' for k in ['data','control','done','error'])
  name=f'{self.n:02d}_{self.slug}'
  (d/f'{name}.svg').write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="900" viewBox="0 0 1600 900"><title>{html.escape(self.title)}</title><defs>{defs}</defs>'+''.join(self.items)+'</svg>\n')
  return {'number':self.n,'file':name,'title':self.title,'nodes':self.nodes,'edges':self.edges}

