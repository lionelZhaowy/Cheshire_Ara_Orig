D='#29292D'; G='#606773'; BLUE='#314D66'; PURPLE='#765489'; GREEN='#187C78'
class Figure:
    def __init__(self,title,subtitle,h):
        self.h=h; self.e=[]; self.n=0; self.boxes=[]
        self.rect(0,0,2400,h,'#FFFFFF',stroke='#FFFFFF')
        self.text(45,57,title,38,bold=True)
        self.text(45,99,subtitle,23,color=G)
    def id(self): self.n+=1; return f'n{self.n:03d}'
    def text(self,x,y,s,size=23,color=D,bold=False,mid=False):
        self.e.append(f'<text id="{self.id()}" x="{x}" y="{y}" font-family="Microsoft YaHei" font-size="{size}" font-weight="{"bold" if bold else "normal"}" text-anchor="{"middle" if mid else "start"}" fill="{color}">{escape(s)}</text>')
    def rect(self,x,y,w,h,fill='#FFFFFF',stroke=D,dash=False):
        self.e.append(f'<rect id="{self.id()}" x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}" stroke="{stroke}" stroke-width="1.8"'+(' stroke-dasharray="8 5"' if dash else '')+'/>')
    def poly(self,pts,fill='#FFFFFF',stroke=D):
        self.e.append(f'<polygon id="{self.id()}" points="'+ ' '.join(f'{x},{y}' for x,y in pts)+f'" fill="{fill}" stroke="{stroke}" stroke-width="1.8" stroke-linejoin="miter"/>')
    def line(self,pts,color=BLUE,arrow=True,dash=False):
        self.e.append(f'<polyline id="{self.id()}" points="'+' '.join(f'{x},{y}' for x,y in pts)+f'" fill="none" stroke="{color}" stroke-width="2.4" stroke-linejoin="miter"'+(f' marker-end="url(#a{color[1:]})"' if arrow else '')+(' stroke-dasharray="7 5"' if dash else '')+'/>')
    def node(self,x,y,w,h,lines,fill='#FFFFFF',size=24):
        self.rect(x,y,w,h,fill)
        top=y+h/2-(len(lines)-1)*30/2+8
        for i,s in enumerate(lines):self.text(x+w/2,top+30*i,s,size if i==0 else 21,bold=i==0,mid=True)
    def panel(self,x,y,w,h,title,fill):
        self.rect(x,y,w,h,fill,stroke='#645C5D')
        self.text(x+20,y+37,title,27,bold=True)
    def mux(self,x,y,w,h,label,fill='#E8DFED'):
        self.poly([(x,y),(x+w,y+28),(x+w,y+h-28),(x,y+h)],fill)
        self.text(x+w/2,y+h/2+8,label,24,bold=True,mid=True)
    def flop(self,x,y,w,h,name,sub='clk_i / rst_ni'):
        self.node(x,y,w,h,[name,sub],'#D8E8F4',23)
        self.line([(x,y+h-28),(x+12,y+h-20),(x,y+h-12)],D,False)
    def fifo(self,x,y,w,h,name,depth):
        self.node(x,y,w,h,[name,depth],'#D8E8F4',23)
        self.line([(x+9,y+9),(x+9,y+h-9)],D,False)
        self.line([(x+17,y+9),(x+17,y+h-9)],D,False)
    def tag(self,x,y,s,color=GREEN):
        self.rect(x,y,74,34,'#FFFFFF',color)
        self.text(x+37,y+24,s,20,color,True,True)
    def dot(self,x,y,color=GREEN):
        self.e.append(f'<circle id="{self.id()}" cx="{x}" cy="{y}" r="4" fill="{color}" stroke="{color}" stroke-width="1"/>')
    def finish(self):
        defs=''.join(f'<marker id="a{c[1:]}" markerUnits="strokeWidth" markerWidth="3" markerHeight="3" viewBox="0 0 3 3" refX="3" refY="1.5" orient="auto-start-reverse"><polygon points="0,0 3,1.5 0,3" fill="{c}"/></marker>' for c in [BLUE,PURPLE,GREEN,D])
        return f'<svg xmlns="http://www.w3.org/2000/svg" width="2400" height="{self.h}" viewBox="0 0 2400 {self.h}">\n<defs>{defs}</defs>\n'+'\n'.join(self.e)+'\n</svg>\n'

